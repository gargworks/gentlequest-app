// Eidetic — Telegram Bot Worker
//
// Lets any Telegram user run `/eidetic <question>` in any chat (private, group,
// channel-admin DM) and have it answered by THEIR own eideticd daemon (exposed
// via Cloudflare tunnel). The Worker is a thin webhook-secret-verifying relay;
// no engram or message content is ever stored here. The user's bridge URL +
// bearer token live in Workers KV, keyed by Telegram user_id (see ADR-020 —
// no PII beyond Telegram numeric IDs).
//
// Routes:
//   GET  /healthz                          — Worker liveness probe.
//   POST /telegram/webhook                 — Telegram Update receiver.
//                                            Verifies `X-Telegram-Bot-Api-Secret-Token`
//                                            against env.WEBHOOK_SECRET (constant-
//                                            time compare). ALWAYS returns 200,
//                                            even on bad input — see § "Why 200
//                                            on everything".
//   GET  /telegram-setup                   — HTML form: paste bot token + bridge
//                                            URL + bridge token + telegram user_id.
//   POST /telegram-setup                   — Form submit handler; verifies bot
//                                            token via getMe, then writes config
//                                            to KV.
//   GET  /telegram-setup/install/<token>   — One-time webhook installer. Calls
//                                            Telegram's setWebhook with this
//                                            Worker's /telegram/webhook URL +
//                                            WEBHOOK_SECRET.
//
// Secrets (wrangler secret put):
//   WEBHOOK_SECRET     — Random 32-byte hex string. Generated by the operator
//                        once via `openssl rand -hex 32`. Telegram echoes it
//                        back in every webhook POST via the
//                        `X-Telegram-Bot-Api-Secret-Token` header (we set it
//                        when calling setWebhook). The Worker rejects any
//                        webhook whose header does not match this secret.
//   ADMIN_BOT_TOKEN    — (optional) Telegram bot token used ONLY by the
//                        /telegram-setup/install path when the user hasn't
//                        passed a token in the URL. Most installs use the
//                        path-param form; this is a convenience for operators
//                        running a single bot.
//
// KV bindings:
//   EIDETIC_TELEGRAM_KV  — namespace storing user:<telegram_user_id>
//                          values: JSON {bridge_url, token, configured_at}
//
// Trust boundary (per ADR-020, mirroring slack-app + discord-bot):
//   - Bridge URL + bearer token ARE customer-provided sensitive data.
//   - Stored in Workers KV (encryption-at-rest = Cloudflare-managed key).
//   - Only Telegram user_id is retained as key. Chat_id is captured at
//     ask-time to address the reply, but is NEVER persisted.
//   - Token is read only on the synchronous /telegram/webhook path and
//     forwarded to the user's own bridge URL over HTTPS. Never logged.
//   - Message text is NEVER persisted (only held in memory for the duration
//     of the request, to build the reply).
//
// ---------------------------------------------------------------------------
// Webhook secret verification approach
// ---------------------------------------------------------------------------
// Telegram's webhook auth model differs sharply from Slack's HMAC and
// Discord's Ed25519. When you call `setWebhook` you pass a `secret_token`
// parameter — Telegram echoes that exact string back in the
// `X-Telegram-Bot-Api-Secret-Token` header on every webhook POST. There is
// no payload signature; verification is a single equality check against a
// shared secret.
//
// We do a **constant-time** byte-by-byte compare so a timing attacker can't
// learn the secret one character at a time. The naive `===` comparison
// short-circuits on the first mismatching byte, which on a fast-enough
// network can leak the prefix.
//
// ---------------------------------------------------------------------------
// Why 200 on everything
// ---------------------------------------------------------------------------
// Telegram's webhook delivery retries aggressively (and indefinitely with
// exponential backoff) on any non-2xx response. A misbehaving Worker that
// returns 4xx/5xx on a malformed update will get the same update redelivered
// for hours. We therefore:
//   1. Always return 200 from /telegram/webhook, even on bad secret / bad
//      JSON / unsupported update type.
//   2. Log the rejection cause to console.warn (visible in `wrangler tail`)
//      so the operator can debug without DOS-ing the Worker.
//
// The single exception is the setup/install routes, which Telegram does NOT
// retry — those return real HTTP statuses for browser-friendly errors.

const BRIDGE_FETCH_TIMEOUT_MS = 12_000;
const TOP_ENGRAMS = 3;
const ENGRAM_SNIPPET_CHARS = 240;
const COMMAND_NAME = "eidetic";
const SETUP_URL_PUBLIC = "https://eidetic.works/telegram-setup";
const TELEGRAM_API_BASE = "https://api.telegram.org";

// ---------------------------------------------------------------------------
// Router
// ---------------------------------------------------------------------------

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    if (url.pathname === "/healthz") {
      return json({ ok: true, service: "eidetic-telegram" });
    }

    if (url.pathname === "/telegram/webhook") {
      if (request.method !== "POST") {
        // GET-ing the webhook is harmless; reply with a hint but still 200
        // so any accidental browser visit doesn't trip Telegram-style retry
        // anywhere in the stack.
        return new Response("telegram webhook endpoint (POST only)", { status: 405 });
      }
      return handleWebhook(request, env, ctx);
    }

    if (url.pathname === "/telegram-setup") {
      if (request.method === "GET")  return renderSetupPage(url);
      if (request.method === "POST") return handleSetupSubmit(request, env);
      return new Response("method not allowed", { status: 405 });
    }

    // /telegram-setup/install/<bot_token> — one-shot webhook installer.
    if (url.pathname.startsWith("/telegram-setup/install/")) {
      if (request.method !== "GET") {
        return new Response("method not allowed", { status: 405 });
      }
      const botToken = url.pathname.slice("/telegram-setup/install/".length);
      return handleInstallWebhook(botToken, request, env);
    }

    return new Response("not found", { status: 404 });
  },
};

// ---------------------------------------------------------------------------
// /telegram/webhook — secret-token-verified update handler
// ---------------------------------------------------------------------------

async function handleWebhook(request, env, ctx) {
  // 1. Verify the secret-token header before reading the body. If this fails
  //    we MUST still return 200 — see "Why 200 on everything" above — so
  //    Telegram doesn't redeliver. We log the rejection for operator debug.
  const headerSecret = request.headers.get("x-telegram-bot-api-secret-token") || "";
  if (!env.WEBHOOK_SECRET || !constantTimeEqual(headerSecret, env.WEBHOOK_SECRET)) {
    console.warn("telegram: bad webhook secret token (returning 200 to suppress retries)");
    return new Response("ok", { status: 200 });
  }

  let update;
  try {
    update = await request.json();
  } catch {
    console.warn("telegram: invalid JSON in webhook body");
    return new Response("ok", { status: 200 });
  }

  // We handle ONLY message.text starting with `/eidetic`. Everything else
  // (edited_message, channel_post, callback_query, my_chat_member, …) is
  // intentionally ignored — return 200 silently so Telegram stops retrying.
  const msg = update.message;
  const text = msg?.text || "";
  if (!msg || typeof text !== "string") {
    return new Response("ok", { status: 200 });
  }

  // Match `/eidetic` or `/eidetic@BotName` at the start (Telegram appends
  // the bot username in group chats).
  const cmdMatch = text.match(/^\/eidetic(?:@\w+)?(?:\s+(.*))?$/s);
  if (!cmdMatch) {
    return new Response("ok", { status: 200 });
  }

  const question = (cmdMatch[1] || "").trim();
  const userId = String(msg.from?.id || "");
  const chatId = msg.chat?.id;
  const messageId = msg.message_id;

  // Telegram's bot token is the same secret we use to call sendMessage. The
  // user picks WHICH bot via the setup flow — their KV entry includes the
  // bot token they configured. We pull it from KV alongside bridge_url+token.
  if (!userId || chatId == null) {
    console.warn("telegram: missing user_id / chat_id");
    return new Response("ok", { status: 200 });
  }

  // We respond asynchronously via Telegram's sendMessage API. The webhook
  // response body is unused (we already 200'd). ctx.waitUntil keeps the
  // Worker alive while we hit the bridge + Telegram.
  ctx.waitUntil(answerAndReply({ env, userId, chatId, messageId, question }));

  return new Response("ok", { status: 200 });
}

async function answerAndReply({ env, userId, chatId, messageId, question }) {
  const config = await loadUserConfig(env, userId);
  if (!config) {
    await telegramReply({
      botToken: env.ADMIN_BOT_TOKEN || "",
      chatId,
      replyToMessageId: messageId,
      text:
        `Configure your bridge URL at ${escapeMdV2(SETUP_URL_PUBLIC)} ` +
        `\\(one\\-time; use your Telegram user ID: \`${escapeMdV2(userId)}\`\\)\\.`,
    });
    return;
  }

  if (!question) {
    await telegramReply({
      botToken: config.bot_token,
      chatId,
      replyToMessageId: messageId,
      text: "Usage: `/eidetic <your question>`",
    });
    return;
  }

  try {
    const data = await askBridge(config.bridge_url, config.token, question);
    await telegramReply({
      botToken: config.bot_token,
      chatId,
      replyToMessageId: messageId,
      text: renderAnswerMarkdown(question, data),
    });
  } catch (err) {
    await telegramReply({
      botToken: config.bot_token,
      chatId,
      replyToMessageId: messageId,
      text: `Bridge call failed: ${escapeMdV2(truncate(String(err.message || err), 200))}`,
    });
  }
}

async function askBridge(bridgeUrl, token, question) {
  const url = `${bridgeUrl.replace(/\/+$/, "")}/ask?question=${encodeURIComponent(question)}`;
  const controller = new AbortController();
  const t = setTimeout(() => controller.abort(), BRIDGE_FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      headers: { Authorization: `Bearer ${token}` },
      signal: controller.signal,
    });
    if (!res.ok) {
      throw new Error(`bridge HTTP ${res.status}`);
    }
    return await res.json();
  } finally {
    clearTimeout(t);
  }
}

async function telegramReply({ botToken, chatId, replyToMessageId, text }) {
  if (!botToken) {
    console.warn("telegram: cannot send reply — no bot token (user not configured?)");
    return;
  }
  const url = `${TELEGRAM_API_BASE}/bot${botToken}/sendMessage`;
  const body = {
    chat_id: chatId,
    text: truncate(text, 4000), // Telegram cap is 4096; leave margin for safety.
    parse_mode: "MarkdownV2",
    reply_parameters: { message_id: replyToMessageId },
    disable_web_page_preview: true,
  };
  try {
    const res = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
    });
    if (!res.ok) {
      const errBody = await res.text().catch(() => "");
      console.warn(`telegram: sendMessage HTTP ${res.status}: ${errBody.slice(0, 300)}`);
    }
  } catch (err) {
    console.warn(`telegram: sendMessage threw: ${String(err.message || err).slice(0, 300)}`);
  }
}

// ---------------------------------------------------------------------------
// Answer rendering — Telegram MarkdownV2
// ---------------------------------------------------------------------------
//
// Telegram MarkdownV2 is strict: any of `_*[]()~\`>#+-=|{}.!` outside of
// matched markdown constructs must be backslash-escaped or Telegram returns
// 400 "can't parse entities". We build the message as plain text first,
// escape each free-form field, then assemble with controlled markdown.

function renderAnswerMarkdown(question, data) {
  const answer = data.answer || data.instructions || data.response || "";
  const items  = data.results || data.engrams || data.hits || [];
  const top    = Array.isArray(items) ? items.slice(0, TOP_ENGRAMS) : [];

  const lines = [];

  // Title: bold the question.
  lines.push(`*${escapeMdV2(truncate(question, 240))}*`);
  lines.push("");

  if (answer) {
    lines.push(escapeMdV2(truncate(answer, 2800)));
  }

  if (top.length > 0) {
    lines.push("");
    lines.push("__Top engrams__");
    for (const r of top) {
      const surface = String(r.surface || r.meta?.surface || "—");
      const ts      = String(r.ts || r.timestamp || "");
      const snippet = truncate(String(r.payload || r.text || ""), ENGRAM_SNIPPET_CHARS);
      // Each engram = bold surface · italic timestamp, newline, escaped snippet.
      lines.push(`*${escapeMdV2(surface)}* · _${escapeMdV2(ts)}_`);
      lines.push(escapeMdV2(snippet || "(empty)"));
      lines.push("");
    }
  } else if (!answer) {
    lines.push("_No matching engrams\\._");
  }

  return lines.join("\n");
}

// MarkdownV2 escape — per https://core.telegram.org/bots/api#markdownv2-style
// Characters that MUST be escaped outside markdown constructs:
//   _ * [ ] ( ) ~ ` > # + - = | { } . !
// We additionally escape backslash itself (must come FIRST so we don't
// double-escape the backslashes we just inserted).
function escapeMdV2(s) {
  return String(s)
    .replace(/\\/g, "\\\\")
    .replace(/([_*\[\]()~`>#+\-=|{}.!])/g, "\\$1");
}

// ---------------------------------------------------------------------------
// Constant-time string compare
// ---------------------------------------------------------------------------
//
// Telegram's secret-token header is a fixed string (we set it via
// setWebhook). A naive `a === b` short-circuits on the first mismatched
// byte, leaking the secret prefix to a timing attacker. This routine
// compares every byte regardless of mismatch.
//
// We compare lengths first (length is not a secret — it's whatever the
// operator chose) and then accumulate XOR-differences across a length-equal
// buffer. Returns false if either input is empty.

function constantTimeEqual(a, b) {
  if (typeof a !== "string" || typeof b !== "string") return false;
  if (a.length === 0 || b.length === 0) return false;
  if (a.length !== b.length) return false;
  let mismatch = 0;
  for (let i = 0; i < a.length; i++) {
    mismatch |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return mismatch === 0;
}

