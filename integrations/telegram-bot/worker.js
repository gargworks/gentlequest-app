async function handleSetupSubmit(request, env) {
  const rawBody = await request.text();
  const form = parseFormUrlEncoded(rawBody);
  const userId    = (form.telegram_user_id || "").trim();
  const botToken  = (form.bot_token        || "").trim();
  const bridgeUrl = (form.bridge_url       || "").trim();
  const token     = (form.token            || "").trim();

  if (!/^\d{5,15}$/.test(userId)) {
    return new Response(
      "Telegram user ID must be a 5–15 digit numeric ID. Ask @userinfobot for yours.",
      { status: 400 },
    );
  }
  if (!/^\d+:[A-Za-z0-9_-]{30,}$/.test(botToken)) {
    return new Response(
      "Bot token format looks wrong. It should be `<digits>:<mixed-case-token>` straight from @BotFather.",
      { status: 400 },
    );
  }
  if (!isAllowedBridgeUrl(bridgeUrl)) {
    return new Response(
      "Bridge URL must be HTTPS on *.trycloudflare.com or *.cloudflare.com. " +
      "Wider hostnames are intentionally rejected so a misconfigured install " +
      "can't be redirected at an arbitrary internet endpoint.",
      { status: 400 },
    );
  }
  if (!token || token.length < 16) {
    return new Response(
      "Bearer token looks too short — paste the full contents of ~/.eidetic/bridge-token.",
      { status: 400 },
    );
  }

  // Verify the bot token by calling getMe. This catches typos and revoked
  // tokens before we commit anything to KV. Telegram's getMe is a cheap
  // unauthenticated-from-outside endpoint (auth is the token in the URL).
  const meRes = await fetch(`${TELEGRAM_API_BASE}/bot${botToken}/getMe`).catch(() => null);
  if (!meRes || !meRes.ok) {
    const status = meRes ? meRes.status : "no-response";
    return new Response(
      `Could not verify bot token via Telegram getMe (HTTP ${status}). ` +
      `Re-check the token from @BotFather.`,
      { status: 400 },
    );
  }
  const me = await meRes.json().catch(() => ({}));
  if (!me.ok || !me.result?.is_bot) {
    return new Response(
      `Telegram getMe returned a non-bot response. Re-check the token from @BotFather.`,
      { status: 400 },
    );
  }

  await env.EIDETIC_TELEGRAM_KV.put(
    kvKey(userId),
    JSON.stringify({
      bot_token: botToken,
      bridge_url: bridgeUrl,
      token,
      configured_at: new Date().toISOString(),
    }),
  );

  const botUsername = String(me.result.username || "your bot");
  const html = `<!doctype html><meta charset="utf-8">
<title>Saved</title>
<body style="font: 16px/1.5 system-ui, sans-serif; max-width: 560px; margin: 4rem auto; padding: 0 1rem;">
<h1>Saved.</h1>
<p>Bot verified as <code>@${escapeHtml(botUsername)}</code>.</p>
<p>Next step: install the webhook so Telegram knows to forward updates here.
   Visit
   <a href="/telegram-setup/install/${escapeHtml(botToken)}">/telegram-setup/install/&lt;bot-token&gt;</a>
   once (the link above already has your token baked in).</p>
<p>Then send <code>/eidetic &lt;your question&gt;</code> to <code>@${escapeHtml(botUsername)}</code>
   in any chat. The Worker will route through your bridge URL and reply.</p>
</body>`;
  return new Response(html, {
    status: 200,
    headers: { "Content-Type": "text/html; charset=utf-8" },
  });
}

// Bridge URL allowlist — same posture as slack-app / discord-bot.
function isAllowedBridgeUrl(raw) {
  let u;
  try { u = new URL(raw); } catch { return false; }
  if (u.protocol !== "https:") return false;
  const host = u.hostname.toLowerCase();
  return host.endsWith(".trycloudflare.com") || host.endsWith(".cloudflare.com");
}

// ---------------------------------------------------------------------------
// /telegram-setup/install/<bot_token> — one-shot setWebhook caller
// ---------------------------------------------------------------------------
//
// Calls Telegram's setWebhook with this Worker's /telegram/webhook URL +
// WEBHOOK_SECRET. After this call, Telegram will POST every update for the
// given bot to our Worker, and echo the secret back in the
// X-Telegram-Bot-Api-Secret-Token header.
//
// We accept the bot token in the URL path rather than a form field so the
// user can run the install with a single browser GET (or curl). The token
// shows up in Cloudflare logs unless the operator strips request URLs — see
// README §Privacy for the trade-off.

async function handleInstallWebhook(botTokenFromPath, request, env) {
  const botToken = botTokenFromPath || env.ADMIN_BOT_TOKEN || "";
  if (!botToken) {
    return new Response(
      "Missing bot token. Visit /telegram-setup/install/<your-bot-token> or " +
      "set ADMIN_BOT_TOKEN on the Worker.",
      { status: 400 },
    );
  }
  if (!/^\d+:[A-Za-z0-9_-]{30,}$/.test(botToken)) {
    return new Response("Bot token format looks wrong.", { status: 400 });
  }
  if (!env.WEBHOOK_SECRET) {
    return new Response(
      "WEBHOOK_SECRET is not set on this Worker. Run " +
      "`wrangler secret put WEBHOOK_SECRET` first.",
      { status: 500 },
    );
  }

  const workerOrigin = new URL(request.url).origin;
  const webhookUrl   = `${workerOrigin}/telegram/webhook`;

  // setWebhook is documented at https://core.telegram.org/bots/api#setwebhook.
  // We pass `allowed_updates: ["message"]` to suppress everything we don't
  // handle (edited_message, channel_post, …) — this is a soft preference;
  // we already drop those on the receive side.
  const params = new URLSearchParams({
    url: webhookUrl,
    secret_token: env.WEBHOOK_SECRET,
    drop_pending_updates: "true",
    allowed_updates: JSON.stringify(["message"]),
  });
  const swRes = await fetch(`${TELEGRAM_API_BASE}/bot${botToken}/setWebhook`, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: params.toString(),
  }).catch((err) => ({ ok: false, _err: err }));

  if (!swRes || !swRes.ok) {
    const status = swRes && swRes.status ? swRes.status : "no-response";
    let detail = "";
    if (swRes && typeof swRes.text === "function") {
      detail = (await swRes.text().catch(() => "")) || "";
    }
    return new Response(
      `Telegram setWebhook failed (HTTP ${status}). ${truncate(detail, 400)}`,
      { status: 502 },
    );
  }
  const swBody = await swRes.json().catch(() => ({}));
  if (!swBody.ok) {
    return new Response(
      `Telegram setWebhook returned ok=false: ${escapeHtml(String(swBody.description || "unknown"))}`,
      { status: 502 },
    );
  }

  const html = `<!doctype html><meta charset="utf-8">
<title>Webhook installed</title>
<body style="font: 16px/1.5 system-ui, sans-serif; max-width: 560px; margin: 4rem auto; padding: 0 1rem;">
<h1>Webhook installed.</h1>
<p>Telegram will now POST updates for your bot to
   <code>${escapeHtml(webhookUrl)}</code> with the secret token attached.</p>
<p>Send <code>/eidetic &lt;your question&gt;</code> to your bot to test.</p>
<p><small>If you ever rotate <code>WEBHOOK_SECRET</code> on the Worker, re-visit
   this URL to refresh Telegram's stored copy.</small></p>
</body>`;
  return new Response(html, {
    status: 200,
    headers: { "Content-Type": "text/html; charset=utf-8" },
  });
}

// ---------------------------------------------------------------------------
// KV helpers
// ---------------------------------------------------------------------------

function kvKey(userId) {
  return `user:${userId}`;
}

async function loadUserConfig(env, userId) {
  const raw = await env.EIDETIC_TELEGRAM_KV.get(kvKey(userId));
  if (!raw) return null;
  try { return JSON.parse(raw); } catch { return null; }
}

// ---------------------------------------------------------------------------
// Generic helpers
// ---------------------------------------------------------------------------

function parseFormUrlEncoded(body) {
  const out = {};
  for (const pair of body.split("&")) {
    if (!pair) continue;
    const eq = pair.indexOf("=");
    const k = eq === -1 ? pair : pair.slice(0, eq);
    const v = eq === -1 ? "" : pair.slice(eq + 1);
    out[decodeURIComponent(k.replace(/\+/g, " "))] =
      decodeURIComponent(v.replace(/\+/g, " "));
  }
  return out;
}

function json(obj, status = 200) {
  return new Response(JSON.stringify(obj), {
    status,
    headers: { "Content-Type": "application/json" },
  });
}

function truncate(s, n) {
  if (!s) return "";
  return s.length > n ? `${s.slice(0, n - 1)}…` : s;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
