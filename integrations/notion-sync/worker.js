async function handleSetupSubmit(request, env) {
  const rawBody = await request.text();
  const form = parseFormUrlEncoded(rawBody);
  const adminSecret  = (form.admin_secret  || "").trim();
  const notionToken  = (form.notion_token  || "").trim();
  const dbId         = (form.db_id         || "").trim().replace(/-/g, "");
  const bridgeUrl    = (form.bridge_url    || "").trim();
  const bridgeToken  = (form.bridge_token  || "").trim();

  if (!env.ADMIN_SECRET || !constantTimeEqual(adminSecret, env.ADMIN_SECRET)) {
    return new Response("Invalid admin secret.", { status: 403 });
  }
  if (!/^[A-Za-z0-9_]{20,}$/.test(notionToken)) {
    return new Response(
      "Notion token looks wrong. Expected the value from notion.so/my-integrations " +
      "(starts with 'secret_' or 'ntn_', 20+ chars).",
      { status: 400 },
    );
  }
  if (!/^[a-f0-9]{32}$/i.test(dbId)) {
    return new Response(
      "Database ID must be the 32-character hex blob from the DB URL " +
      "(dashes are stripped automatically).",
      { status: 400 },
    );
  }
  if (!isAllowedBridgeUrl(bridgeUrl)) {
    return new Response(
      "Bridge URL must be HTTPS on *.trycloudflare.com or *.cloudflare.com. " +
      "Wider hostnames are intentionally rejected so a misconfigured install " +
      "can't be redirected at an arbitrary internet endpoint.",
      { status: 400 },
    );
  }
  if (!bridgeToken || bridgeToken.length < 16) {
    return new Response(
      "Bearer token looks too short — paste the full contents of ~/.eidetic/bridge-token.",
      { status: 400 },
    );
  }

  // Verify the Notion token via /v1/users/me. Cheap call, catches typos.
  const meRes = await notionFetch(`${NOTION_API_BASE}/users/me`, {
    method: "GET",
    notionToken,
  }).catch(() => null);
  if (!meRes || !meRes.ok) {
    const status = meRes ? meRes.status : "no-response";
    return new Response(
      `Could not verify Notion token via /v1/users/me (HTTP ${status}). ` +
      `Re-check the token from notion.so/my-integrations.`,
      { status: 400 },
    );
  }

  // Verify the integration has actually been shared on the DB. Without this
  // the user discovers the failure only at first poll, which is bad UX.
  const dbRes = await notionFetch(
    `${NOTION_API_BASE}/databases/${encodeURIComponent(dbId)}`,
    { method: "GET", notionToken },
  ).catch(() => null);
  if (!dbRes || !dbRes.ok) {
    const status = dbRes ? dbRes.status : "no-response";
    return new Response(
      `Notion DB lookup failed (HTTP ${status}). Most likely the DB is not ` +
      `shared with this integration — open it in Notion, click "..." → ` +
      `Add connections, and pick your integration.`,
      { status: 400 },
    );
  }

  const cfg = {
    notion_token: notionToken,
    db_id: dbId,
    bridge_url: bridgeUrl,
    bridge_token: bridgeToken,
    configured_at: new Date().toISOString(),
  };
  await env.EIDETIC_NOTION_KV.put(userKey(), JSON.stringify(cfg));
  // Maintain a reverse index db_id → config-key so webhook routing can find
  // the user from a webhook payload that only carries the DB ID.
  await env.EIDETIC_NOTION_KV.put(dbIndexKey(dbId), userKey());

  const html = `<!doctype html><meta charset="utf-8">
<title>Saved</title>
<body style="font: 16px/1.5 system-ui, sans-serif; max-width: 560px; margin: 4rem auto; padding: 0 1rem;">
<h1>Saved.</h1>
<p>Trigger an initial sync with:</p>
<pre><code>curl -H "X-Admin-Secret: &lt;your-admin-secret&gt;" \\
     https://${escapeHtml(new URL(request.url).host)}/notion/poll</code></pre>
<p>The first call will sync every page in the DB (checkpoint is empty).
   Subsequent calls only sync pages with <code>last_edited_time</code> newer
   than the checkpoint.</p>
<p>For continuous sync add a cron entry that hits <code>/notion/poll</code>
   every 15 minutes — or wire up Notion's webhook beta to
   <code>/notion/webhook</code>.</p>
</body>`;
  return new Response(html, {
    status: 200,
    headers: { "Content-Type": "text/html; charset=utf-8" },
  });
}

// Bridge URL allowlist — same posture as slack-app / discord-bot / telegram-bot.
function isAllowedBridgeUrl(raw) {
  let u;
  try { u = new URL(raw); } catch { return false; }
  if (u.protocol !== "https:") return false;
  const host = u.hostname.toLowerCase();
  return host.endsWith(".trycloudflare.com") || host.endsWith(".cloudflare.com");
}

// ---------------------------------------------------------------------------
// KV helpers
// ---------------------------------------------------------------------------
//
// Single-tenant Worker → one config key. We hash nothing here because the
// ADMIN_SECRET gates writes; the key is just a fixed string.

function userKey() { return "user:default"; }
function dbIndexKey(dbId) { return `db_index:${dbId}`; }

async function loadConfigByAdminSecret(env) {
  const raw = await env.EIDETIC_NOTION_KV.get(userKey());
  if (!raw) return null;
  try { return JSON.parse(raw); } catch { return null; }
}

async function loadConfigByDbId(env, dbId) {
  const key = await env.EIDETIC_NOTION_KV.get(dbIndexKey(dbId));
  if (!key) return null;
  const raw = await env.EIDETIC_NOTION_KV.get(key);
  if (!raw) return null;
  try { return JSON.parse(raw); } catch { return null; }
}

// ---------------------------------------------------------------------------
// Constant-time string compare (same pattern as telegram-bot)
// ---------------------------------------------------------------------------

function constantTimeEqual(a, b) {
  if (typeof a !== "string" || typeof b !== "string") return false;
  if (a.length === 0 || b.length === 0) return false;
  if (a.length !== b.length) return false;
  let mismatch = 0;
  for (let i = 0; i < a.length; i++) {
    mismatch |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return mismatch === 0;
}

// ---------------------------------------------------------------------------
// Generic helpers
// ---------------------------------------------------------------------------

function parseFormUrlEncoded(body) {
  const out = {};
  for (const pair of body.split("&")) {
    if (!pair) continue;
    const eq = pair.indexOf("=");
    const k = eq === -1 ? pair : pair.slice(0, eq);
    const v = eq === -1 ? "" : pair.slice(eq + 1);
    out[decodeURIComponent(k.replace(/\+/g, " "))] =
      decodeURIComponent(v.replace(/\+/g, " "));
  }
  return out;
}

function json(obj, status = 200) {
  return new Response(JSON.stringify(obj), {
    status,
    headers: { "Content-Type": "application/json" },
  });
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
